function luaString(value) {
  return `"${value.replaceAll("\\", "\\\\").replaceAll('"', '\\"')}"`;
}

export function compileAddonKnowledge({ season, dungeons }) {
  if (season?.recordType !== "season") throw new TypeError("season must be a WHELP season record");
  const byId = new Map(dungeons.map((dungeon) => [dungeon.id, dungeon]));
  const records = season.dungeons.map((entry) => {
    const dungeon = byId.get(entry.id);
    if (!dungeon) throw new Error(`missing dungeon record ${entry.id}`);
    if (dungeon.challengeMapId !== entry.challengeMapId) throw new Error(`challengeMapId mismatch for ${entry.id}`);
    if (dungeon.validity?.fromBuild !== season.validity?.fromBuild) throw new Error(`build mismatch for ${entry.id}`);
    const enemies = [...dungeon.enemies].sort((left, right) => left.npcId - right.npcId);
    return { dungeon, enemies };
  }).sort((left, right) => left.dungeon.challengeMapId - right.dungeon.challengeMapId);
  const revisionPayload = records.map(({ dungeon, enemies }) => ({
    id: dungeon.id,
    challengeMapId: dungeon.challengeMapId,
    instanceMapId: dungeon.instanceMapId,
    enemyForcesTotal: dungeon.enemyForcesTotal,
    enemies: enemies.map((enemy) => [enemy.npcId, enemy.enemyForces]),
  }));
  const datasetHash = createHash("sha256").update(JSON.stringify({
    schemaVersion: 1,
    seasonId: season.id,
    dataBuild: season.validity.fromBuild,
    dungeons: revisionPayload,
  })).digest("hex");

  const lines = [
    "-- Generated by npm run generate:addon-knowledge. Do not edit by hand.",
    "local _, WHELP = ...",
    "",
    "WHELP.GeneratedKnowledge = {",
    "    schemaVersion = 1,",
    `    dataBuild = ${luaString(season.validity.fromBuild)},`,
    `    datasetHash = ${luaString(datasetHash)},`,
    `    seasonId = ${luaString(season.id)},`,
    "    dungeons = {",
  ];
  for (const { dungeon, enemies } of records) {
    lines.push(`        [${dungeon.challengeMapId}] = {`);
    lines.push(`            id = ${luaString(dungeon.id)},`);
    lines.push(`            instanceMapId = ${dungeon.instanceMapId},`);
    lines.push(`            enemyForcesTotal = ${dungeon.enemyForcesTotal},`);
    lines.push("            enemies = {");
    for (const enemy of enemies) lines.push(`                [${enemy.npcId}] = ${enemy.enemyForces},`);
    lines.push("            },");
    lines.push("        },");
  }
  lines.push("    },", "}", "");
  return lines.join("\n");
}
import { createHash } from "node:crypto";
